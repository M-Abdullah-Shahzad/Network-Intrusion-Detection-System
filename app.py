import json
import os
from pathlib import Path

import joblib
import pandas as pd
import streamlit as st

from model_utils import classification_metrics, prepare_features


st.set_page_config(page_title="NIDS | Network Intrusion Detection", layout="wide")
st.title("Network Intrusion Detection System")
st.caption("UNSW-NB15 machine-learning experiment. Upload network-flow records using the dataset feature schema.")


@st.cache_resource
def load_artifacts():
    model_dir = Path(os.getenv("NIDS_MODEL_DIR", "models"))
    required = [
        "scaler.pkl", "kmeans_model.pkl", "knn_model.pkl",
        "naive_bayes_model.pkl", "feature_columns.json", "raw_feature_columns.json", "metrics.json",
    ]
    missing = [name for name in required if not (model_dir / name).is_file()]
    if missing:
        raise FileNotFoundError(f"Missing artifacts in {model_dir}: {', '.join(missing)}")
    return {
        "scaler": joblib.load(model_dir / "scaler.pkl"),
        "kmeans": joblib.load(model_dir / "kmeans_model.pkl"),
        "knn": joblib.load(model_dir / "knn_model.pkl"),
        "naive_bayes": joblib.load(model_dir / "naive_bayes_model.pkl"),
        "feature_columns": json.loads((model_dir / "feature_columns.json").read_text(encoding="utf-8")),
        "raw_feature_columns": json.loads((model_dir / "raw_feature_columns.json").read_text(encoding="utf-8")),
        "metrics": json.loads((model_dir / "metrics.json").read_text(encoding="utf-8")),
    }


try:
    artifacts = load_artifacts()
except Exception as exc:
    st.error(f"Model artifacts are not ready: {exc}")
    st.info("Download the UNSW-NB15 train/test CSV files into data/ and run python train_and_save_models.py.")
    st.stop()


tab_metrics, tab_inspector = st.tabs(["Held-out Model Evaluation", "Traffic CSV Inspector"])

with tab_metrics:
    st.subheader("Evaluation on the UNSW-NB15 test split")
    metrics = artifacts["metrics"]
    st.write(
        f"Training rows: **{metrics['train_rows']:,}** · "
        f"Test rows: **{metrics['test_rows']:,}** · "
        f"Encoded features: **{metrics['feature_count']:,}**"
    )
    rows = [
        {"Model": name, **values}
        for name, values in metrics["models"].items()
    ]
    st.dataframe(
        pd.DataFrame(rows).set_index("Model").style.format("{:.3f}"),
        use_container_width=True,
    )
    st.caption("Metrics are generated by the training script from the supplied held-out test CSV.")
    st.info("K-Means is unsupervised. Its cluster IDs are not equivalent to normal/attack labels.")


with tab_inspector:
    st.subheader("Inspect network-flow records")
    uploaded = st.file_uploader(
        "Upload a CSV with UNSW-NB15 feature columns",
        type=["csv"],
        help="The id, label, and attack_cat columns are excluded from model inputs.",
    )
    model_name = st.selectbox("Select model", ["KNN", "Naive Bayes", "K-Means"])

    if uploaded is not None:
        try:
            raw = pd.read_csv(uploaded)
            missing_columns = [
                column for column in artifacts["raw_feature_columns"]
                if column not in raw.columns
            ]
            if missing_columns:
                raise ValueError(
                    "CSV is missing required UNSW-NB15 feature columns: "
                    + ", ".join(missing_columns[:12])
                )
            features = prepare_features(raw, artifacts["feature_columns"])
            scaled = artifacts["scaler"].transform(features)

            if model_name == "KNN":
                predictions = artifacts["knn"].predict(scaled)
            elif model_name == "Naive Bayes":
                predictions = artifacts["naive_bayes"].predict(scaled)
            else:
                predictions = artifacts["kmeans"].predict(scaled)

            results = pd.DataFrame({
                "row_number": range(1, len(raw) + 1),
                "model_output": predictions,
            })

            if model_name == "K-Means":
                results["interpretation"] = [
                    f"Cluster {int(value)} — cluster IDs are not attack labels"
                    for value in predictions
                ]
                st.warning("K-Means returns cluster IDs only; it does not identify an attack without separate cluster interpretation.")
            else:
                results["prediction"] = [
                    "Attack" if int(value) == 1 else "Normal"
                    for value in predictions
                ]
                if "label" in raw.columns:
                    actual = pd.to_numeric(raw["label"], errors="coerce")
                    valid = actual.notna()
                    if valid.any():
                        valid_predictions = pd.Series(predictions, index=raw.index)[valid]
                        observed = classification_metrics(actual[valid].astype(int), valid_predictions)
                        st.write("Uploaded file evaluation (rows with a valid label):")
                        st.json(observed)

            st.dataframe(results, use_container_width=True, hide_index=True)
            st.download_button(
                "Download predictions CSV",
                data=results.to_csv(index=False).encode("utf-8"),
                file_name="nids_predictions.csv",
                mime="text/csv",
            )
        except Exception as exc:
            st.error(f"Could not process the uploaded CSV: {exc}")
